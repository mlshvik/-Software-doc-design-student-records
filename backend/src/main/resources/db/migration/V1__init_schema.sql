-- =====================================================================
-- V1: початкова схема БД «Система обліку студентів у ВНЗ»
-- =====================================================================

CREATE TABLE faculty (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL UNIQUE,
    short_name  VARCHAR(20)  NOT NULL
);

CREATE TABLE specialty (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(10)  NOT NULL,
    name        VARCHAR(200) NOT NULL,
    faculty_id  BIGINT       NOT NULL REFERENCES faculty (id),
    CONSTRAINT uk_specialty_code_faculty UNIQUE (code, faculty_id)
);

CREATE TABLE study_group (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(20) NOT NULL UNIQUE,
    specialty_id    BIGINT      NOT NULL REFERENCES specialty (id),
    course          INTEGER     NOT NULL CHECK (course BETWEEN 1 AND 6),
    admission_year  INTEGER     NOT NULL
);

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT')),
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE student (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name           VARCHAR(100) NOT NULL,
    first_name          VARCHAR(100) NOT NULL,
    middle_name         VARCHAR(100),
    email               VARCHAR(150),
    record_book_number  VARCHAR(20)  NOT NULL UNIQUE,
    phone               VARCHAR(20),
    birth_date          DATE,
    group_id            BIGINT       NOT NULL REFERENCES study_group (id),
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE'
                        CHECK (status IN ('ACTIVE', 'ACADEMIC_LEAVE', 'EXPELLED', 'GRADUATED')),
    user_id             BIGINT UNIQUE REFERENCES app_user (id)
);
CREATE INDEX idx_student_group ON student (group_id);
CREATE INDEX idx_student_last_name ON student (last_name);

CREATE TABLE teacher (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name        VARCHAR(100) NOT NULL,
    first_name       VARCHAR(100) NOT NULL,
    middle_name      VARCHAR(100),
    email            VARCHAR(150),
    position         VARCHAR(100),
    academic_degree  VARCHAR(100),
    department       VARCHAR(200),
    user_id          BIGINT UNIQUE REFERENCES app_user (id)
);

CREATE TABLE subject (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200)  NOT NULL,
    credits       NUMERIC(4, 1) NOT NULL CHECK (credits > 0),
    hours         INTEGER       NOT NULL CHECK (hours > 0),
    control_type  VARCHAR(20)   NOT NULL CHECK (control_type IN ('EXAM', 'CREDIT', 'DIFF_CREDIT'))
);

CREATE TABLE teaching_assignment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id     BIGINT     NOT NULL REFERENCES subject (id),
    teacher_id     BIGINT     NOT NULL REFERENCES teacher (id),
    group_id       BIGINT     NOT NULL REFERENCES study_group (id),
    semester       INTEGER    NOT NULL CHECK (semester BETWEEN 1 AND 12),
    academic_year  VARCHAR(9) NOT NULL,
    CONSTRAINT uk_assignment_subject_group_semester UNIQUE (subject_id, group_id, semester, academic_year)
);
CREATE INDEX idx_assignment_teacher ON teaching_assignment (teacher_id);
CREATE INDEX idx_assignment_group ON teaching_assignment (group_id);

CREATE TABLE grade (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT      NOT NULL REFERENCES student (id),
    assignment_id  BIGINT      NOT NULL REFERENCES teaching_assignment (id),
    score          INTEGER     NOT NULL CHECK (score BETWEEN 0 AND 100),
    attempt        VARCHAR(30) NOT NULL DEFAULT 'REGULAR'
                   CHECK (attempt IN ('REGULAR', 'RETAKE_TEACHER', 'RETAKE_COMMISSION')),
    graded_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    graded_by_id   BIGINT REFERENCES teacher (id),
    CONSTRAINT uk_grade_student_assignment_attempt UNIQUE (student_id, assignment_id, attempt)
);
CREATE INDEX idx_grade_student ON grade (student_id);
CREATE INDEX idx_grade_assignment ON grade (assignment_id);

CREATE TABLE academic_debt (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT      NOT NULL REFERENCES student (id),
    assignment_id  BIGINT      NOT NULL REFERENCES teaching_assignment (id),
    status         VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
    opened_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at      TIMESTAMP
);
CREATE INDEX idx_debt_student ON academic_debt (student_id);
CREATE INDEX idx_debt_status ON academic_debt (status);

CREATE TABLE schedule_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id  BIGINT      NOT NULL REFERENCES teaching_assignment (id) ON DELETE CASCADE,
    day_of_week    VARCHAR(10) NOT NULL
                   CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY')),
    pair_number    INTEGER     NOT NULL CHECK (pair_number BETWEEN 1 AND 8),
    week_type      VARCHAR(5)  NOT NULL DEFAULT 'ALL' CHECK (week_type IN ('ALL', 'ODD', 'EVEN')),
    classroom      VARCHAR(20) NOT NULL,
    lesson_type    VARCHAR(10) NOT NULL CHECK (lesson_type IN ('LECTURE', 'PRACTICE', 'LAB'))
);
CREATE INDEX idx_schedule_time ON schedule_entry (day_of_week, pair_number);

CREATE TABLE notification (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    message       VARCHAR(500) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_read       BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_notification_recipient ON notification (recipient_id);

CREATE TABLE system_setting (
    setting_key    VARCHAR(100) PRIMARY KEY,
    setting_value  VARCHAR(255) NOT NULL,
    description    VARCHAR(255)
);
